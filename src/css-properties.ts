/** Đích alias trong SHORT_PROPERTIES không thuộc danh sách property chuẩn. */
const NON_STANDARD_ALIAS_TARGETS = new Set(['-webkit-line-clamp', '-webkit-text-fill-color', '-webkit-text-stroke', '-webkit-text-stroke-color', '-webkit-text-stroke-width', 'font-synthesis-position'])

let standardList: readonly string[] | null = null
/**
 * Danh sách tên property CSS chuẩn (đã sắp xếp). Hàm (dựng lần đầu gọi) thay vì hằng: bản CDN `tailwind-auto`
 * (không từ điển) không gọi nên bundler bỏ cả danh sách lẫn SHORT_PROPERTIES.
 */
export const standardCssProperties = (): readonly string[] =>
    (standardList ??= [...new Set([...STANDARD_NOT_IN_DICTIONARY, ...Object.values(SHORT_PROPERTIES).filter((name) => !NON_STANDARD_ALIAS_TARGETS.has(name))])].sort())

const VENDOR_PREFIXED = /^-(?:webkit|moz|ms|o)-[a-z][a-z0-9-]*$/
const CUSTOM_PROPERTY = /^--[a-zA-Z0-9_-]+$/

/** Tên property không cần có trong từ điển: tiền tố nhà cung cấp hoặc custom property. */
export const isOpenPropertyName = (name: string): boolean =>
    VENDOR_PREFIXED.test(name) || CUSTOM_PROPERTY.test(name)
